"""Ad coverage per target platform: every platform a title targets that offers an ad kind the
title commits to must be reached by a placement of that kind - in the integration plan, and
in the bundle that ships.

Why it is one module (2026-10-21): Y8 returned a game the Factory built with "the game is
missing ads". Its integration plan (src/platform/integration-plan.ts, generated by the sdk
step) listed its placements for the platforms of the original design (crazygames, yandex,
poki); the title was retargeted to yandex, crazygames and y8, and the y8 build - with
game.config.yaml monetization.ad_kinds [interstitial, rewarded] - made no ad call. The
runtime (gameplay.ts) shows a placement on a target only when its `platforms` is null or
lists the target. The sdk step reported y8's interstitial `not-required` ("the design places
none"), and verify, the quality gate and platform-validate had nothing that asked. Three
readers now ask the same question through this module:

  * the sdk step (wgf_sdk.integration): a target whose profile offers a committed kind gets
    the kind's placements when the design's lists predate it, and a gap left is a failed
    feature, never `not-required`;
  * verify (wgf_verification.checks.platform): `platform.ads-integrated:<id>`, on the plan
    in the checkout and on the platform's own bundle;
  * platform-validate (wgf_publish.validate): guard `ads_integrated`, on verify's check and
    the package archive.

    requirements(config, profile_for)  -> [Requirement]: (platform, kind, portal requires ads)
    parse_plan(text)                   -> the plan as data (PlanUnreadable when it is not)
    covers(plan, kind, target)         -> whether a placement reaches the target at runtime
    gaps(plan, requirements)           -> the requirements no placement reaches
    plan_targets(text) / stale(...)    -> the targets the plan was generated for, and why it
                                          no longer matches game.config.yaml
    bundle_placements(texts)           -> the plan's placements as compiled into a bundle

The rule reads the plan exactly as gameplay.ts does: a placement matches by the TARGET id
(never by an adapter substitute), and an interstitial is also reached when the target is in
`breakOnContinue` (the runtime signals the portal's own ad opportunity on every continue).
The template applies the same rule to the game side (`pnpm sdk:check`, web-game-template
scripts/sdk/ad-coverage.mjs, 1.2.3).

Standard library only; reads text, runs nothing.
"""

import json
import re

__all__ = ["AD_KINDS", "PLAN_FILE", "TARGETS_MARK", "Requirement", "PlanUnreadable",
           "committed", "offered", "required_by_portal", "requirements", "parse_plan",
           "plan_targets", "targets_line", "covers", "listed_for", "gaps", "stale",
           "bundle_placements", "bundle_covers"]

AD_KINDS = ("interstitial", "rewarded")
PLAN_FILE = "src/platform/integration-plan.ts"
# The line the sdk step writes into the plan's header: the targets it was generated for.
TARGETS_MARK = "// Targets:"


class PlanUnreadable(ValueError):
    """The integration plan's text holds no INTEGRATION_PLAN literal this module can read."""


class Requirement:
    """One target platform that must be reached by a placement of one ad kind."""

    __slots__ = ("platform", "kind", "portal_required")

    def __init__(self, platform, kind, portal_required):
        self.platform = platform
        self.kind = kind
        # The profile says the portal itself requires ads (`ads.required_by_portal`): a gap
        # is a Hard Gate there, and reported as a warning elsewhere.
        self.portal_required = portal_required

    def __repr__(self):
        return f"Requirement({self.platform!r}, {self.kind!r}, {self.portal_required!r})"

    def __eq__(self, other):
        return isinstance(other, Requirement) and (self.platform, self.kind,
                                                   self.portal_required) == (
            other.platform, other.kind, other.portal_required)

    def __hash__(self):
        return hash((self.platform, self.kind, self.portal_required))


def committed(game_config):
    """The ad kinds game.config.yaml monetization.ad_kinds commits the title to."""
    kinds = ((game_config or {}).get("monetization") or {}).get("ad_kinds") or []
    return [str(k) for k in kinds if isinstance(k, str)]


def offered(profile):
    """The ad kinds a platform profile's `capabilities.ads` offers."""
    return [str(k) for k in ((profile or {}).get("capabilities") or {}).get("ads") or []]


def required_by_portal(profile):
    """Whether the profile records that the portal requires ads (`ads.required_by_portal`)."""
    return ((profile or {}).get("ads") or {}).get("required_by_portal") is True


def _platform_ids(game_config):
    out = []
    for entry in (game_config or {}).get("platforms") or []:
        pid = entry.get("id") if isinstance(entry, dict) else entry
        if isinstance(pid, str) and pid:
            out.append(pid)
    return out


def requirements(game_config, profile_for):
    """[Requirement] for every target and every committed kind its profile offers.

    `profile_for(platform_id)` returns the profile the build is judged by (the pinned one),
    or None when there is none - a target with no profile requires nothing here; the
    profile's own check (`platform.profile:<id>`) says it is missing."""
    kinds = committed(game_config)
    out = []
    if not kinds:
        return out
    for pid in _platform_ids(game_config):
        profile = profile_for(pid)
        if profile is None:
            continue
        portal = required_by_portal(profile)
        for kind in kinds:
            if kind in AD_KINDS and kind in offered(profile):
                out.append(Requirement(pid, kind, portal))
    return out


# -- the integration plan -------------------------------------------------------------------

_KEY = re.compile(r"^(\s*)([A-Za-z_$][\w$]*)\s*:", re.M)
_TRAILING_COMMA = re.compile(r",(\s*[}\]])")


def _strip_comments(text):
    """Comments out, string contents kept: a `//` inside a string literal stays."""
    out, i, n = [], 0, len(text)
    while i < n:
        char = text[i]
        if char in "\"'`":
            end = i + 1
            while end < n and text[end] != char:
                end += 2 if text[end] == "\\" else 1
            out.append(text[i:end + 1])
            i = end + 1
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end == -1 else end + 2
        else:
            out.append(char)
            i += 1
    return "".join(out)


def _literal(text):
    """The `{...}` assigned to INTEGRATION_PLAN, or None."""
    declared = re.search(r"\bINTEGRATION_PLAN\b[^=]*=", text)
    if not declared:
        return None
    start = text.find("{", declared.end())
    if start == -1:
        return None
    depth, i, n = 0, start, len(text)
    while i < n:
        char = text[i]
        if char in "\"'`":
            end = i + 1
            while end < n and text[end] != char:
                end += 2 if text[end] == "\\" else 1
            i = end + 1
            continue
        if char in "{[":
            depth += 1
        elif char in "}]":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1
    return None


def parse_plan(text):
    """The plan generated by the sdk step (wgf_sdk.integrate.render_plan) as data.

    The generator writes JSON values with identifier keys, one per line, and trailing commas;
    a hand-written plan in the same shape reads too. Anything else raises PlanUnreadable:
    a plan nobody can read is never taken to cover a platform."""
    literal = _literal(_strip_comments(text or ""))
    if literal is None:
        raise PlanUnreadable(f"{PLAN_FILE} declares no INTEGRATION_PLAN object literal")
    as_json = _TRAILING_COMMA.sub(r"\1", _KEY.sub(r'\1"\2":', literal))
    try:
        plan = json.loads(as_json)
    except ValueError as exc:
        raise PlanUnreadable(f"INTEGRATION_PLAN in {PLAN_FILE} is not the generated literal "
                             f"shape ({exc})")
    if not isinstance(plan, dict) or not isinstance(plan.get("placements"), list):
        raise PlanUnreadable(f"INTEGRATION_PLAN in {PLAN_FILE} has no placements list")
    return plan


def targets_line(platform_ids):
    """The header line the sdk step writes: the targets the plan was generated for."""
    return f"{TARGETS_MARK} {', '.join(platform_ids) if platform_ids else '(none)'}"


def plan_targets(text):
    """The targets the plan's header says it was generated for, or None when the plan
    predates the header (a plan the sdk step wrote before 2.8.3)."""
    for line in (text or "").splitlines()[:8]:
        if line.startswith(TARGETS_MARK):
            rest = line[len(TARGETS_MARK):].strip()
            if rest == "(none)":
                return []
            return [p.strip() for p in rest.split(",") if p.strip()]
    return None


def stale(text, game_config):
    """Why the plan no longer matches game.config.yaml's targets, or None when it does.

    A plan with no Targets header predates it and is reported as such - stale for a
    target its placements do not reach, which `gaps` says."""
    recorded = plan_targets(text)
    current = _platform_ids(game_config)
    if recorded is None:
        return (f"{PLAN_FILE} records no targets (generated before the sdk step wrote them): "
                f"whether it was made for {', '.join(current) or 'no platform'} is unknown")
    added = [p for p in current if p not in recorded]
    dropped = [p for p in recorded if p not in current]
    if not added and not dropped:
        return None
    parts = []
    if added:
        parts.append(f"targets added since: {', '.join(added)}")
    if dropped:
        parts.append(f"targets dropped since: {', '.join(dropped)}")
    return (f"{PLAN_FILE} was generated for {', '.join(recorded) or 'no platform'}; "
            f"game.config.yaml targets {', '.join(current) or 'none'} ({'; '.join(parts)}): "
            "the plan is stale - run the sdk step again")


def _reaches(platforms, target):
    return platforms is None or (isinstance(platforms, list) and target in platforms)


def covers(plan, kind, target):
    """Whether a placement of `kind` in `plan` reaches `target` at runtime (gameplay.ts)."""
    for placement in (plan or {}).get("placements") or []:
        if isinstance(placement, dict) and placement.get("kind") == kind \
                and _reaches(placement.get("platforms"), target):
            return True
    return kind == "interstitial" and target in ((plan or {}).get("breakOnContinue") or [])


def listed_for(plan, kind):
    """The platforms the plan's placements of `kind` name ("every platform" for null)."""
    out = []
    for placement in (plan or {}).get("placements") or []:
        if not isinstance(placement, dict) or placement.get("kind") != kind:
            continue
        platforms = placement.get("platforms")
        for pid in (["every platform"] if platforms is None else platforms or []):
            if pid not in out:
                out.append(pid)
    return out


def gaps(plan, required):
    """The requirements no placement of the plan reaches."""
    return [r for r in required if not covers(plan, r.kind, r.platform)]


# -- the compiled bundle --------------------------------------------------------------------
#
# The plan is data in the bundle: the minifier keeps an object literal's keys and its string
# values (`{id:"interstitial-game-over",kind:"interstitial",moment:"game-over",trigger:"...",
# platforms:["crazygames","yandex","poki"]}`). Keys may come out quoted; strings in any quote.

_Q = "[\"'`]"
# Inside one object literal: anything but a brace or a quote, or a whole string (a trigger
# may hold braces: "After a lost run: {retry}").
_BODY = (r"(?:[^{}\"'`]|\"(?:[^\"\\]|\\.)*\"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`)*?")
_BUNDLE_PLACEMENT = re.compile(
    rf"\{{{_BODY}{_Q}?\bkind{_Q}?\s*:\s*{_Q}(?P<kind>interstitial|rewarded){_Q}{_BODY}"
    rf"{_Q}?\bplatforms{_Q}?\s*:\s*(?P<platforms>null|\[[^\]]*\])")
_BUNDLE_STRING = re.compile(rf"{_Q}([^\"'`]*){_Q}")


def bundle_placements(texts):
    """[(kind, platforms or None)] for every plan placement found in the bundle's text."""
    found = []
    for text in texts:
        for match in _BUNDLE_PLACEMENT.finditer(text):
            raw = match.group("platforms")
            platforms = None if raw == "null" else _BUNDLE_STRING.findall(raw)
            entry = (match.group("kind"), platforms)
            if entry not in found:
                found.append(entry)
    return found


def bundle_covers(placements, kind, target, break_on_continue=()):
    """Whether the bundle's placements (bundle_placements) reach `target` with `kind`."""
    if any(k == kind and _reaches(p, target) for k, p in placements):
        return True
    return kind == "interstitial" and target in break_on_continue
