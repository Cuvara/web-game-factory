    def outcomes(self, vid, recs):
        oc = recs.get("outcomes")
        if not isinstance(oc, dict):
            for cid in ("win", "lose", "restart"):
                self.emit(cid, vid, "blocked", "the spec recorded no end states on this viewport")
            return
        if oc.get("error"):
            note = f" (the run stopped: {oc['error'][:120]})"
        else:
            note = ""
        win = oc.get("win")
        if "win_started" not in oc:
            self.emit("win", vid, "unmeasured", "the design states no win")
        elif not isinstance(win, dict):
            self.emit("win", vid, "blocked", "play never started for the win run" + note)
        elif win.get("reached") == "won":
            self.emit("win", vid, "pass", "the oracle reached won")
        elif win.get("reached") == "lost":
            self.emit("win", vid, "fail", "the oracle, playing well, lost on this viewport")
        else:
            self.emit("win", vid, "unmeasured", f"won not reached within {win.get('window_ms', 0) / 1000:.0f} s "
                      "(the playability step judges win.reachable over its own window)" + note)
        lose = oc.get("lose")
        if not isinstance(lose, dict):
            self.emit("lose", vid, "blocked", "play never started for the lose run" + note)
            self.emit("restart", vid, "blocked", "no lost state to restart from" + note)
            return
        if lose.get("reached") == "lost":
            self.emit("lose", vid, "pass", "bad play reached lost")
        else:
            self.emit("lose", vid, "unmeasured", f"lost not reached within "
                      f"{lose.get('window_ms', 0) / 1000:.0f} s of bad play" + note)
            self.emit("restart", vid, "unmeasured", "no lost state to restart from")
            return
        restart = oc.get("restart") or {}
        if restart.get("reached") == "playing":
            self.emit("restart", vid, "pass", f"back in play {restart.get('took_ms')} ms after "
                      f"{restart.get('how')}")
        elif not restart.get("how"):
            self.emit("restart", vid, "fail", "the lost screen offers no retry (probe input or button)")
        else:
            self.emit("restart", vid, "fail", f"{restart.get('how')} did not return to play within "
                      f"{restart.get('window_ms', 0) / 1000:.0f} s")

