"""Browser QA: the built game in a real browser at every viewport a player brings.

    core/reference/browser-qa.yaml (viewports, checks, tiers, bars)
      -> browser_qa.spec.ts copied into the checkout's git-ignored build/wgf-browser-qa/,
         run with the repository's own Playwright against `pnpm preview` of the build,
         one project per viewport, behind the refusing network proxy
      -> records per viewport (viewport, outcomes, perf, clips)       [measure]
      -> judge(): every check of the contract, as Check objects        [decide]

The spec records and never judges; `judge` holds the records to the contract's bars, so the
judging is tested offline from recorded fixtures (scripts/tests/test_browser_qa.py) and the
same records always give the same checks.

Tiers (browser-qa.yaml): `hard` checks are required at every quality tier; `quality` checks
are required where the run's quality-tier class is in `quality_required_at` (the release
class, as shipped) and are WARNINGs elsewhere; `advisory` checks are never required. A check
that measured nothing is never a PASS: BLOCKED where it is required and the measurement was
possible (the spec did not run, the host was degraded on every attempt), a WARNING where the
game has nothing of that kind to measure (no pause control, no mute control). A check the
build could have been measured on but whose data it OMITS - the play probe reports no
gameplay-critical entity, or no audio level; the bundle ships no runtime manifest - is held
as core/reference/quality-policy.yaml `skipped_checks` says (wgflib.check_strength): at a tier
whose class is under `not_passed_at` (release) it is BLOCKED and required, never a note the
quality floor could pass over; elsewhere a WARNING.

Timing checks re-use the playability bot's host-health judgement
(wgf_playability.analysis.environment_health, with visual-quality.yaml `environment`): a
recording whose last attempt was degraded is BLOCKED, never passed and never failed.
"""

